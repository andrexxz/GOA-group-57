// 1) Scope არის ის გარემო სადაც ვრცელდება ცვლადები და ფუნქციები. არსებობს გლობალური და ლოკალური სკოპი. გლობალური სკოპი არის ის სადაც ცვლადები და ფუნქციები ხელმისაწვდომია ყველგან, ხოლო ლოკალური სკოპი არის ის სადაც ცვლადები და ფუნქციები ხელმისაწვდომია მხოლოდ კონკრეტულ ბლოკში ან ფუნქციაში.

// მაგალითი გლობალური სკოპის:
let globalVar = "Hello, World!";
function greet() {
    console.log(globalVar); // ხელმისაწვდომია
}
greet();
console.log(globalVar); // ხელმისაწვდომია
// მაგალითი ლოკალური სკოპის:
function localScopeExample() {
    let localVar = "Hello, Local!";
    console.log(localVar); // ხელმისაწვდომია
}
localScopeExample();
// console.log(localVar); // შეცდომა: localVar არ არის განსაზღვრული


// 2) Hoisting არის JavaScript-ის მექანიზმი, რომელიც საშუალებას აძლევს ცვლადებს და ფუნქციებს "მოიმწყვდიონ" მათი დეკლარაციის წინ. ეს ნიშნავს, რომ შეგიძლიათ გამოიყენოთ ცვლადები და ფუნქციები მათი დეკლარაციის წინ, თუმცა ცვლადების შემთხვევაში მხოლოდ var ტიპის ცვლადები არიან ჰოისტირებული.

// მაგალითი ჰოისტინგის:
console.log(hoistedVar); // undefined
var hoistedVar = "I am hoisted!";
hoistedFunction(); // "I am a hoisted function!"
function hoistedFunction() {
    console.log("I am a hoisted function!");
}


// 3) var-ის გამოყენება ცუდია, რადგან ის არ არის ბლოკ-სკოპირებული, რაც შეიძლება გამოიწვიოს გაუგებრობები და შეცდომები კოდის მუშაობაში. ასევე, var-ის ჰოისტინგი შეიძლება გამოიწვიოს გაუთვალისწინებელი შედეგები.
// მაგალითი var-ის პრობლემის:
if (true) {
    var x = 10;
}
console.log(x); // 10, რადგან var არ არის ბლოკ-სკოპირებული  
// უკეთესი იქნება let ან const-ის გამოყენება:
if (true) {
    let y = 20;
}
// console.log(y); // შეცდომა: y არ არის განსაზღვრული


// 4) აროუ ფუნქციებსა და ჩვეულებრივ ფუნქციებს შორის არსებობს რამდენიმე განსხვავება:
// აროუ ფუნქციები არის ფუნქციები, რომლებიც არ არის დეკლარებული, მაგრამ გამოიყენება. მაგალითად:
const arrowFunction = () => {
    console.log("I am an arrow function!");
};
arrowFunction();
// ჩვეულებრივი ფუნქციების შემთხვევაში, თუ ფუნქციასთვის დეკლარაცია გადმოწყვეტილია, 
// ოპტიმუმში, JavaScript-ში, "function" -სთვის "hoisting" -ზე გადმოწყვეტილობა 
// (function declaration hoisting) -ზე.

function regularFunction() {
    console.log("I am a regular function!");
}
regularFunction();
// აროუ ფუნქციებს არ აქვთ საკუთარი "this" კონტექსტი, ისინი იღებენ "this" მნიშვნელობას გარე კონტექსტიდან, ხოლო ჩვეულებრივ ფუნქციებს აქვთ საკუთარი "this" კონტექსტი. 
// ასევე, აროუ ფუნქციები არ შეიძლება გამოყენებულ იქნას როგორც კონსტრუქტორები (new ოპერატორის გამოყენებით), მაშინ როცა ჩვეულებრივ ფუნქციებს შეუძლიათ.

